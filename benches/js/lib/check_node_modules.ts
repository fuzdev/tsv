/**
 * Preflight for the harness dependencies (`benches/js/node_modules`, installed
 * by `deno task bench:install`) — shared by the bench, smoke, and every
 * corpus/conformance comparison entry point (plus `scripts/doctor.ts` via the
 * non-exiting probe).
 *
 * Missing → fatal with the installer hint: without it the canonical impls
 * (prettier + svelte/compiler + acorn) fail later with an opaque
 * module-resolution error. Stale → fatal too: the run would use the OLD installed
 * versions while reports label them with the new pins. `BENCH_STALE_OK=1`
 * downgrades stale (never missing) to a warning, mirroring
 * `check_artifact_freshness.ts`.
 *
 * **Staleness is a CONTENT question, asked of content.** Each pinned dep's
 * installed `package.json` `version` is compared against the pin — the thing the
 * check actually cares about, reported per package (`prettier: pinned 3.9.6,
 * installed 3.9.5`). The earlier form compared `package.json`'s MTIME against
 * npm's `.package-lock.json` install stamp, which is a proxy that fails in both
 * directions: editing a comment in `package.json`, or a branch switch restamping
 * it, demanded a reinstall that would change nothing, while an install that ran
 * but did not take (a pruned optional binding, a resolution that landed
 * elsewhere) refreshed the stamp and read as fresh.
 *
 * The `force_installed` pins are graded too (today only the oxc wasi binding — see
 * `OXC_WASI_BINDING` in `versions.ts`), since `dependencies` is not where they live.
 *
 * Cost is ~20 small reads issued together, once per process — immaterial beside the
 * run it guards.
 *
 * Runtime-neutral (node: builtins only) — runs under Deno, Node, and Bun.
 *
 * ⚠ It must STAY npm-free, and not only for portability: its job is to report a
 * MISSING `node_modules` with the installer hint, which a bare specifier anywhere in
 * its import graph would pre-empt with an opaque resolution error. `versions.ts`, its
 * only non-builtin import, is bound by a stricter form of the same rule:
 * `install_deps.ts` imports it, and that is the one entry point that runs BEFORE
 * `node_modules` exists, so a bare specifier there would leave `deno task
 * bench:install` — the command whose job is to create what everything else
 * preflights — unable to run on a fresh clone.
 */

import { readFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

import { EXACT_PIN, read_dependency_pins, read_force_installed_pins } from './versions.ts';

/**
 * The preflight's verdict. Unexported: `probe_node_modules` returns it across the
 * module boundary (`scripts/doctor.ts` is a caller, deliberately — it wants the
 * side-effect-free path rather than `check_node_modules`'s exit), but every
 * consumer reads `.status` / `.message` structurally, so nothing needs to NAME
 * the type.
 */
type NodeModulesStatus =
	{ status: 'ok' } | { status: 'missing'; message: string } | { status: 'stale'; message: string };

/** What `node_modules/<name>/package.json` says, or why it said nothing. */
type InstalledProbe =
	| { kind: 'version'; version: string | undefined }
	| { kind: 'absent' }
	| { kind: 'unreadable'; message: string };

/**
 * Read one installed package's `version`. Absent and unreadable stay DISTINCT: a
 * package that isn't there is a normal install outcome with a known remedy, while a
 * package whose manifest won't parse is a broken tree, and reporting the second as
 * the first sends the reader to re-run an installer that already succeeded.
 */
async function probe_installed(name: string): Promise<InstalledProbe> {
	try {
		const content = await readFile(
			fileURLToPath(new URL(`../node_modules/${name}/package.json`, import.meta.url)),
			'utf8'
		);
		return { kind: 'version', version: (JSON.parse(content) as { version?: string }).version };
	} catch (e) {
		// Structural `code` read rather than a `NodeJS.ErrnoException` cast: all three
		// runtimes set it on their `node:fs` errors, and none of them needs the global
		// node namespace to be in scope for the check to type.
		if ((e as { code?: string }).code === 'ENOENT') return { kind: 'absent' };
		return { kind: 'unreadable', message: e instanceof Error ? e.message : String(e) };
	}
}

/**
 * How `probe` fails `pin`, as one reportable line, or `null` when it matches.
 *
 * One spelling of the grading, because there are two graders: the `dependencies`
 * sweep and the `force_installed` sweep below. They differ in exactly one thing —
 * whether ABSENCE counts — which the second caller states for itself rather than
 * passing a flag here, keeping the exemption where its reasoning is.
 */
function pin_mismatch(label: string, pin: string, probe: InstalledProbe): string | null {
	switch (probe.kind) {
		case 'absent':
			return `${label}: pinned ${pin}, NOT INSTALLED`;
		case 'unreadable':
			return `${label}: pinned ${pin}, manifest unreadable (${probe.message})`;
		case 'version':
			return probe.version === pin ? null : `${label}: pinned ${pin}, installed ${probe.version}`;
	}
}

/** Inspect `benches/js/node_modules` without side effects (doctor-friendly). */
export async function probe_node_modules(): Promise<NodeModulesStatus> {
	const node_modules = fileURLToPath(new URL('../node_modules', import.meta.url));
	try {
		await stat(node_modules);
	} catch {
		return {
			status: 'missing',
			message:
				`Harness dependencies not installed (${node_modules} missing). ` +
				"Run 'deno task bench:install' first — it installs the npm deps + the oxc wasi binding."
		};
	}

	// Every pinned dep, against what is actually installed. `dependencies` only:
	// `devDependencies` is types-only (`@types/node`), never loaded at runtime, and
	// pinned by range rather than exactly.
	//
	// THROWS if the pins can't be read: "does the install match them" then has no
	// answer, and answering `stale` would put that unanswerable question behind
	// `BENCH_STALE_OK=1`. `lib/versions.ts` throws on this same file moments later
	// for the same reason — which is why the read itself lives there, one spelling
	// of where the pins are and what shape they take.
	const pins = await read_dependency_pins();

	// A range pin (`^4.4.3`) constrains rather than fixes, so any installed version
	// may satisfy it — only exact pins can be checked this way, and they are what the
	// harness's reproducibility rests on.
	const exact = Object.entries(pins).filter(([, spec]) => EXACT_PIN.test(spec));
	const probes = await Promise.all(exact.map(([name]) => probe_installed(name)));

	const mismatches: string[] = [];
	for (const [i, [name, spec]] of exact.entries()) {
		const mismatch = pin_mismatch(name, spec, probes[i]);
		if (mismatch !== null) mismatches.push(mismatch);
	}

	// The `force_installed` pins (today only the oxc wasi binding) live in no
	// `dependencies` entry, so the sweep above cannot see them — and the reports label
	// their rows with them, so an installed copy at a DIFFERENT version is the
	// mislabeling this check exists to prevent. No range filter here: the reader
	// itself refuses a non-exact entry, so every one is gradable. Absence is not
	// graded: nothing is measured then, so nothing is mislabeled, and the report's
	// `unavailable` records the missing row with its load error.
	//
	// An UNREADABLE manifest is graded, though, exactly as it is in the sweep above:
	// unlike absence it says the package is there and may well load, with a version
	// nothing can read — which is the mislabeling case, not the harmless one.
	const forced = Object.entries(await read_force_installed_pins());
	const forced_probes = await Promise.all(forced.map(([name]) => probe_installed(name)));
	for (const [i, [name, spec]] of forced.entries()) {
		const probe = forced_probes[i];
		// The absence exemption, spelled here rather than as a flag into
		// `pin_mismatch`: it is this section's property, not a mode of the grader.
		if (probe.kind === 'absent') continue;
		const mismatch = pin_mismatch(`${name} (force_installed)`, spec, probe);
		if (mismatch !== null) mismatches.push(mismatch);
	}

	if (mismatches.length === 0) return { status: 'ok' };
	return {
		status: 'stale',
		message:
			`benches/js/node_modules does not match the pins in package.json — ` +
			`re-run 'deno task bench:install' so the run measures what the report will label:\n    ` +
			mismatches.join('\n    ')
	};
}

/** Verify `benches/js/node_modules` exists and is not stale; exits the process otherwise. */
export async function check_node_modules(): Promise<void> {
	const probe = await probe_node_modules();
	if (probe.status === 'ok') return;
	if (probe.status === 'stale' && process.env.BENCH_STALE_OK === '1') {
		console.error(`⚠ ${probe.message}\n  (proceeding: BENCH_STALE_OK=1)`);
		return;
	}
	// The stale message lists one mismatch per line, so the escape hint takes its own
	// line rather than trailing the last package and reading as part of it.
	const escape = probe.status === 'stale' ? '\n  (BENCH_STALE_OK=1 to proceed anyway)' : '';
	console.error(`\n✗ ${probe.message}${escape}\n`);
	process.exit(1);
}
