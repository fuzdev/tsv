/**
 * `run_svelte_styles_harvest` over fakes for `git`, the checkout's files, the perf view, and
 * the cache directory: the blocks it keeps and how it dedents them, each concat's bytes, the
 * unchanged and stray paths, the stamp, the freshness rule, and the refusals, each of which
 * writes nothing. Package-free, so it gates in `npm run test:node`.
 */

import { createHash } from 'node:crypto';
import { deepStrictEqual, ok, strictEqual } from 'node:assert';
import { afterEach, beforeEach, test, vi } from 'vitest';

import { GATE_CHECKOUT_IDS, SVELTE_STYLES_BLOCKS_PIN } from '../lib/gate_counts.ts';
import { fake_files, fake_id, fake_stamp_git } from '../lib/harvest_fakes.ts';
import { HARVEST_STAMPS } from '../lib/harvest_stamp_table.ts';
import type { SourceFile } from '../lib/types.ts';
import {
	run_svelte_styles_harvest,
	type SvelteStylesHarvestDeps
} from './svelte_styles_harvest.ts';

const STAMP_PATH = HARVEST_STAMPS['svelte-styles'].path;
const ROOT = '/fake/corpora/collections';
const PINNED = GATE_CHECKOUT_IDS['../corpora'].hash;
const TREE = PINNED.padEnd(40, '0');
const ENTRIES = ['../corpora/collections', 'benches/js/.cache/svelte_styles'];
const FILTER_SOURCE = { 'benches/js/lib/corpus.ts': '// corpus' };
const FILTERS = createHash('sha1')
	.update('benches/js/lib/corpus.ts')
	.update('\0')
	.update('// corpus')
	.update('\0')
	.digest('hex')
	.slice(0, 16);

let err: string[];
beforeEach(() => {
	err = [];
	vi.spyOn(console, 'error').mockImplementation((...a: unknown[]) => void err.push(a.join(' ')));
});
afterEach(() => {
	vi.restoreAllMocks();
});

const svelte = (path: string, content: string, language = 'svelte'): SourceFile =>
	({ path, content, language, bytes: content.length }) as SourceFile;

/** `blocks` one-block components in collection `big`, plus `small`'s mixed component: an
 * indented CSS block, a `lang="scss"` one, an empty one, and an indented `<style>` that the
 * line anchor never sees. */
const perf_files = (blocks = SVELTE_STYLES_BLOCKS_PIN - 1): SourceFile[] => [
	svelte(
		`${ROOT}/small/App.svelte`,
		'<script></script>\n<style lang="css">\n\n\t.a {\n\t\tcolor: red;\n\t}\n\n\t.b {}\n</style>\n' +
			'<style lang="scss">\n$x: 1;\n</style>\n<style>\n  \n</style>\n  <style>\n.not_anchored {}\n</style>\n'
	),
	svelte(`${ROOT}/small/skip.css`, '<style>\n.x{}\n</style>\n', 'css'),
	...Array.from({ length: blocks }, (_, i) =>
		svelte(`${ROOT}/big/c${i}.svelte`, `<style>\n.c${i} {}\n</style>`)
	)
];

const stamp_text = (tree = TREE): string =>
	`{\n\t"corpora_tree": "${tree}",\n\t"blocks_pin": ${SVELTE_STYLES_BLOCKS_PIN},` +
	`\n\t"perf_entries": "${ENTRIES.join(' ')}",\n\t"filters": "${FILTERS}"\n}\n`;

const fake_deps = (
	options: {
		perf?: SourceFile[];
		files?: Record<string, string>;
		styles?: Record<string, string>;
		tree?: string | null;
	} = {}
) => {
	const files = fake_files({ ...FILTER_SOURCE, ...options.files });
	const styles = new Map(Object.entries(options.styles ?? {}));
	const style_log: string[] = [];
	let streams = 0;
	const deps: SvelteStylesHarvestDeps = {
		git: fake_stamp_git(
			options.tree === null ? {} : { '../corpora:collections': options.tree ?? TREE }
		),
		files,
		corpus: {
			view_paths: async () => ENTRIES,
			stream: async function* () {
				streams++;
				yield* options.perf ?? perf_files();
			}
		},
		styles: {
			read_text_if_exists: async (name) => styles.get(name) ?? null,
			write: async (name, data) => {
				style_log.push(`write ${name}`);
				styles.set(name, data);
			},
			list: async function* () {
				for (const name of styles.keys()) yield { name };
			},
			remove: async (name) => {
				style_log.push(`remove ${name}`);
				styles.delete(name);
			}
		},
		collections_root: ROOT
	};
	return { deps, files, styles, style_log, streams: () => streams };
};

const banner = (collection: string, blocks: number): string =>
	`/* generated by \`deno task bench:harvest:svelte-styles\` — CSS extracted from ` +
	`../corpora/collections/${collection}'s .svelte <style> blocks (${blocks} blocks); do not edit */`;

test('each kept block is dedented into its collection concat, strays go, then the stamp', async () => {
	const run = fake_deps({
		styles: { 'gone.css': 'old', 'big.css': 'stale' },
		files: { [STAMP_PATH]: stamp_text(fake_id('old')) }
	});
	strictEqual(await run_svelte_styles_harvest(run.deps, []), 0);
	strictEqual(
		run.styles.get('small.css'),
		`${banner('small', 1)}\n\n.a {\n\tcolor: red;\n}\n\n.b {}\n`
	);
	const big = run.styles.get('big.css')!;
	ok(big.startsWith(`${banner('big', SVELTE_STYLES_BLOCKS_PIN - 1)}\n\n.c0 {}\n\n.c1 {}\n`));
	ok(big.endsWith(`.c${SVELTE_STYLES_BLOCKS_PIN - 2} {}\n`));
	deepStrictEqual(run.style_log, ['write small.css', 'write big.css', 'remove gone.css']);
	deepStrictEqual(run.files.log, ['mkdir benches/js/.cache/svelte_styles', `write ${STAMP_PATH}`]);
	strictEqual(run.files.files.get(STAMP_PATH), stamp_text());
	ok(err.at(-1)!.startsWith(`svelte_styles_harvest: ${SVELTE_STYLES_BLOCKS_PIN} style blocks / `));
	ok(
		err
			.at(-1)!
			.endsWith(
				`from 2 collections → benches/js/.cache/svelte_styles/ (2 written, 0 unchanged, 1 stray removed; ` +
					`stamped at ../corpora:collections ${TREE.slice(0, 9)})`
			)
	);
});

test('a concat whose bytes match is left alone and counted unchanged', async () => {
	const first = fake_deps();
	strictEqual(await run_svelte_styles_harvest(first.deps, []), 0);
	const again = fake_deps({ styles: Object.fromEntries(first.styles) });
	strictEqual(await run_svelte_styles_harvest(again.deps, ['--force']), 0);
	deepStrictEqual(again.style_log, []);
	ok(err.at(-1)!.includes('(0 written, 2 unchanged;'));
});

test('a fresh stamp skips with its line, streaming nothing; --force harvests past it', async () => {
	const fresh = { [STAMP_PATH]: stamp_text(), 'benches/js/.cache/svelte_styles/big.css': '' };
	const skipped = fake_deps({ files: fresh });
	strictEqual(await run_svelte_styles_harvest(skipped.deps, []), 0);
	strictEqual(skipped.streams(), 0);
	deepStrictEqual(err, [
		`svelte_styles_harvest: up to date (../corpora:collections at ${TREE.slice(0, 9)}, ` +
			`${SVELTE_STYLES_BLOCKS_PIN} blocks, same perf entries) — skipping; --force to re-harvest`
	]);
	const forced = fake_deps({ files: fresh });
	strictEqual(await run_svelte_styles_harvest(forced.deps, ['--force']), 0);
	strictEqual(forced.streams(), 1);
});

test('no tree id refuses before anything is read', async () => {
	const run = fake_deps({ tree: null });
	strictEqual(await run_svelte_styles_harvest(run.deps, ['--force']), 1);
	strictEqual(run.streams(), 0);
	deepStrictEqual(err, [
		'svelte_styles_harvest: ../corpora:collections is not a git checkout tree — the perf view ' +
			'reads the corpora snapshot (git clone https://github.com/fuzdev/corpora ../corpora)'
	]);
	deepStrictEqual(run.files.log, []);
});

test('a block from outside the snapshot fails, writing nothing', async () => {
	const run = fake_deps({ perf: [svelte('/elsewhere/X.svelte', '<style>\n.x{}\n</style>')] });
	strictEqual(await run_svelte_styles_harvest(run.deps, []), 1);
	strictEqual(
		err.at(-1),
		'svelte_styles_harvest: perf-view .svelte file outside the snapshot: /elsewhere/X.svelte'
	);
	deepStrictEqual(run.files.log, []);
	deepStrictEqual(run.style_log, []);
});

test('a block count off the pin fails, naming whether the tree is the pinned one', async () => {
	const aligned = fake_deps({ perf: perf_files(SVELTE_STYLES_BLOCKS_PIN) });
	strictEqual(await run_svelte_styles_harvest(aligned.deps, []), 1);
	ok(
		err
			.at(-1)!
			.startsWith(
				`FAIL: ${SVELTE_STYLES_BLOCKS_PIN + 1} style blocks ≠ pinned ${SVELTE_STYLES_BLOCKS_PIN}; cache not written.`
			)
	);
	ok(err.at(-1)!.includes(' — same tree, so either the perf view changed'));
	deepStrictEqual(aligned.files.log, []);
	const skewed = fake_deps({ perf: perf_files(0), tree: fake_id('other') });
	strictEqual(await run_svelte_styles_harvest(skewed.deps, []), 1);
	ok(err.at(-1)!.includes(' — a snapshot refresh moves this deliberately'));
	deepStrictEqual(skewed.style_log, []);
});
