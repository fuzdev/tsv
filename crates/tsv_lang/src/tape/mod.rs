//! The tape's format: the binary parse wire's types, constants and schema tables, which every
//! producer and reader of a tape in Rust shares.
//!
//! The tape is the span-only JSON wire's tree laid down as little-endian `u32` words — a record per
//! object, its fields positional in wire key order, strings as refs into the source or a UTF-8
//! pool — so a JS host builds the same tree `JSON.parse` would without parsing any text: the
//! generated decoder (`crates/tsv_wasm/npm/tape_decode.js`) runs one small function per fast
//! shape. The format is specified in `docs/tape_format.md`; the field table it is derived from is
//! the AST schema table (`crates/tsv_wasm/types/tsv_ast_schema.json`), and [`shapes`] is that
//! table compiled to Rust, generated by `npm run ast-schema:update`.
//!
//! Here rather than beside a producer because the format belongs below every crate that writes
//! or reads a tape: the producer every binding ships is each language crate's wire writer, its
//! tape copy writing into `TapeSink` (the `_json` half below), and the JSON → tape transcoder
//! the gates grade it through, and the printer, are `tsv_debug`'s. Behind this crate's `_tape`
//! feature, which pulls nothing in; tsv's own plumbing, not public API.

#[rustfmt::skip]
pub mod shapes;
#[cfg(feature = "_tape_literals")]
mod literal;
#[cfg(feature = "_json")]
mod sink;
#[cfg(feature = "_tape_literals")]
