/// How a field is laid down on the tape (`docs/tape_format.md` §Field encodings). The
/// discriminants are the codes the generated JS decoder's tables carry.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Enc {
    /// The record's `type`: no words, the entry's constant.
    Type = 0,
    /// One word, an unsigned integer.
    Offset = 1,
    /// One word, `0` or `1`.
    Boolean = 2,
    /// Two words, an `f64`'s little-endian bytes.
    Number = 3,
    /// No words, always `null`.
    Null = 4,
    /// No words: the source text between the record's own `start` and `end`.
    Own = 5,
    /// One word, an index into the field's vocabulary ([`shapes::KEYWORDS`] at `aux`).
    Keyword = 6,
    /// Two words, a string ref.
    Ref = 7,
    /// Two words, a string ref or [`NULL_REF`].
    RefNullable = 8,
    /// A count, then that many string refs.
    Strings = 9,
    /// A nested record; `aux` names the `type`-less entry the position holds, if one.
    Record = 10,
    /// A count, then that many records.
    List = 11,
    /// A tagged value (the `TAG_*` words).
    Value = 12,
}

/// One field of a tape entry.
#[derive(Clone, Copy, Debug)]
pub struct Field {
    /// The wire key.
    pub key: &'static str,
    /// How its value is laid down.
    pub enc: Enc,
    /// Its presence-mask bit, or [`NO_BIT`] when every record of the entry carries it.
    pub bit: u8,
    /// A [`Enc::Keyword`] field's vocabulary index, or the context entry of a [`Enc::Record`]
    /// field holding a `type`-less entry; [`NO_AUX`] otherwise.
    pub aux: u16,
}

/// One tape entry: a wire node type (or a named variant, or a `type`-less object) and its fields
/// in wire order.
#[derive(Clone, Copy, Debug)]
pub struct Entry {
    /// The table identity it was derived from (`Type`, `Type/variant`, `css:Type`, `~Interface`).
    pub name: &'static str,
    /// Its `type` value, `None` for a `type`-less entry.
    pub ty: Option<&'static str>,
    /// Its fields, in wire order.
    pub fields: &'static [Field],
}

/// [`Field::bit`] for a field every record carries.
pub const NO_BIT: u8 = u8::MAX;
/// [`Field::aux`] for a field that names nothing.
pub const NO_AUX: u16 = u16::MAX;

/// The header's first word: the bytes `TSVT`.
pub const MAGIC: u32 = 0x5456_5354;
/// Words in the header.
pub const HEADER_WORDS: usize = 8;
/// A string ref's first word for `null`.
pub const NULL_REF: u32 = 0x8000_0000;
/// The most entries an entry-generic header names (its low bits); the mask sits above them.
pub const MAX_ENTRIES: u32 = 1024;
/// A record header: `null`.
pub const HEADER_NULL: u32 = 0;
/// A record header: a self-describing record (`-1`).
pub const HEADER_ESCAPE: u32 = u32::MAX;

/// Tagged-value tag: `null`.
pub const TAG_NULL: u32 = 0;
/// Tagged-value tag: `false`.
pub const TAG_FALSE: u32 = 1;
/// Tagged-value tag: `true`.
pub const TAG_TRUE: u32 = 2;
/// Tagged-value tag: a number (two words follow).
pub const TAG_NUMBER: u32 = 3;
/// Tagged-value tag: a string (a ref follows).
pub const TAG_STRING: u32 = 4;
/// Tagged-value tag: an array (a count and that many tagged values follow).
pub const TAG_ARRAY: u32 = 5;
/// Tagged-value tag: an object (a record follows).
pub const TAG_OBJECT: u32 = 6;

/// Where each entry's run of fast shapes starts in [`shapes::SHAPES`], which is sorted by entry
/// and then mask: entry `e`'s shapes are `SHAPES[SHAPE_STARTS[e]..SHAPE_STARTS[e + 1]]`.
static SHAPE_STARTS: [u16; shapes::ENTRIES.len() + 1] = shape_starts();

const fn shape_starts() -> [u16; shapes::ENTRIES.len() + 1] {
    let mut starts = [0u16; shapes::ENTRIES.len() + 1];
    let mut entry = 0;
    let mut i = 0;
    while entry <= shapes::ENTRIES.len() {
        while i < shapes::SHAPES.len() && (shapes::SHAPES[i].0 as usize) < entry {
            i += 1;
        }
        starts[entry] = i as u16;
        entry += 1;
    }
    starts
}

/// The fast shape id of an entry and mask, if the shape list holds the pair.
#[must_use]
pub fn shape_id(entry: u16, mask: u32) -> Option<u32> {
    let e = usize::from(entry);
    let (lo, hi) = (
        usize::from(*SHAPE_STARTS.get(e)?),
        usize::from(*SHAPE_STARTS.get(e + 1)?),
    );
    shapes::SHAPES[lo..hi]
        .binary_search_by_key(&mask, |&(_, m)| m)
        .ok()
        .map(|i| (lo + i) as u32 + 1)
}

/// An entry-generic record's header word: `-(2 + (mask << 10 | entry))`.
#[must_use]
pub fn generic_header(entry: u16, mask: u32) -> u32 {
    (2 + mask * MAX_ENTRIES + u32::from(entry)).wrapping_neg()
}

/// The header word of a record of `entry` with presence mask `mask`: its fast shape's id, else
/// its entry-generic header. Every entry's all-required mask (`0`) is a fast shape, the first of
/// its entry's run.
#[must_use]
#[inline]
pub fn header_of(entry: u16, mask: u32) -> u32 {
    if mask == 0 {
        return u32::from(SHAPE_STARTS[usize::from(entry)]) + 1;
    }
    shape_id(entry, mask).unwrap_or_else(|| generic_header(entry, mask))
}

// The compile-time lookups a direct writer's sites make (`tsv_css`'s `entry!` / `bit!` /
// `keyword!`, `tsv_ts`'s site macros), each in a `const` so a name the table lacks fails the
// build. Each is the generated `const fn` match of `shapes` (`entry_named`, `field_named`,
// `keyword_named`) with the miss turned into that build error. No writer asks them at run time:
// a shipped tape copy carries none of the generated matches.

/// The id of the tape entry named `name` (`css:Rule`, `~CSSRuleMetadata`).
#[must_use]
#[expect(
    clippy::panic,
    reason = "a compile-time lookup: evaluated in a `const`, the panic is a build error"
)]
pub const fn entry_id(name: &str) -> u16 {
    match shapes::entry_named(name.as_bytes()) {
        Some(entry) => entry,
        None => panic!("no tape entry of that name"),
    }
}

/// Entry `entry`'s field `key`.
#[must_use]
#[expect(
    clippy::panic,
    reason = "a compile-time lookup: evaluated in a `const`, the panic is a build error"
)]
pub const fn field_of(entry: u16, key: &str) -> Field {
    match shapes::field_named(entry, key.as_bytes()) {
        Some(index) => shapes::ENTRIES[entry as usize].fields[index as usize],
        None => panic!("the tape entry has no field of that key"),
    }
}

/// The presence-mask bit of entry `entry`'s field `key` ([`NO_BIT`] for a required one).
#[must_use]
pub const fn field_bit(entry: u16, key: &str) -> u8 {
    field_of(entry, key).bit
}

/// The `aux` of entry `entry`'s field `key` (a keyword field's vocabulary).
#[must_use]
pub const fn field_aux(entry: u16, key: &str) -> u16 {
    field_of(entry, key).aux
}

/// The index of the keyword `word` in vocabulary `vocab`.
#[must_use]
#[expect(
    clippy::panic,
    reason = "a compile-time lookup: evaluated in a `const`, the panic is a build error"
)]
pub const fn keyword_id(vocab: u16, word: &str) -> u32 {
    match shapes::keyword_named(vocab, word.as_bytes()) {
        Some(index) => index,
        None => panic!("the keyword is outside its vocabulary"),
    }
}

/// [`COMMENT_BITS`]'s value for an entry without that field.
#[cfg(feature = "_tape_literals")]
pub(crate) const NO_COMMENTS: u8 = u8::MAX - 1;

/// Each entry's `leadingComments` and `trailingComments` presence bits ([`NO_COMMENTS`]: the
/// entry has no such field), built from the tables at build time — the one run-time question
/// a writer's comment attach asks (it closes every kind of node), answered by an index rather
/// than a lookup by name.
#[cfg(feature = "_tape_literals")]
pub(crate) static COMMENT_BITS: [[u8; 2]; shapes::ENTRIES.len()] = comment_bits();

#[cfg(feature = "_tape_literals")]
const fn comment_bits() -> [[u8; 2]; shapes::ENTRIES.len()] {
    const fn is(key: &str, name: &str) -> bool {
        let (a, b) = (key.as_bytes(), name.as_bytes());
        if a.len() != b.len() {
            return false;
        }
        let mut i = 0;
        while i < a.len() {
            if a[i] != b[i] {
                return false;
            }
            i += 1;
        }
        true
    }
    let mut bits = [[NO_COMMENTS; 2]; shapes::ENTRIES.len()];
    let mut e = 0;
    while e < shapes::ENTRIES.len() {
        let fields = shapes::ENTRIES[e].fields;
        let mut i = 0;
        while i < fields.len() {
            let f = fields[i];
            let side = if is(f.key, "leadingComments") {
                0
            } else if is(f.key, "trailingComments") {
                1
            } else {
                2
            };
            if side < 2 {
                assert!(
                    matches!(f.enc, Enc::List) && f.bit != NO_COMMENTS && f.bit != NO_BIT,
                    "a comment field is a list with a presence bit"
                );
                bits[e][side] = f.bit;
            }
            i += 1;
        }
        e += 1;
    }
    bits
}

/// What a record's header word says.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Header {
    /// `null`.
    Null,
    /// A self-describing record.
    Escape,
    /// A typed record: its entry and mask (a fast shape's or an entry-generic header's).
    Typed {
        /// The entry id.
        entry: u16,
        /// The presence mask.
        mask: u32,
    },
}

/// Reads a record header, `None` for a word that names no shape or entry.
#[must_use]
pub fn read_header(word: u32) -> Option<Header> {
    match word {
        HEADER_NULL => Some(Header::Null),
        HEADER_ESCAPE => Some(Header::Escape),
        1..NULL_REF => shapes::SHAPES
            .get(word as usize - 1)
            .map(|&(entry, mask)| Header::Typed { entry, mask }),
        _ => {
            let v = word.wrapping_neg() - 2;
            let entry = (v % MAX_ENTRIES) as u16;
            let mask = v / MAX_ENTRIES;
            (usize::from(entry) < shapes::ENTRIES.len()).then_some(Header::Typed { entry, mask })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The per-entry shape runs answer what a search of the whole sorted list answers.
    #[test]
    fn shape_id_is_the_sorted_lists_answer() {
        let search = |entry: u16, mask: u32| {
            shapes::SHAPES
                .binary_search(&(entry, mask))
                .ok()
                .map(|i| i as u32 + 1)
        };
        for &(entry, mask) in &shapes::SHAPES {
            for m in [mask, mask + 1, mask ^ 1, u32::MAX] {
                assert_eq!(shape_id(entry, m), search(entry, m), "({entry}, {m})");
            }
        }
        for entry in 0..=shapes::ENTRIES.len() as u16 + 1 {
            assert_eq!(shape_id(entry, 0), search(entry, 0), "({entry}, 0)");
        }
    }

    /// `header_of` is the fast shape's id where the list holds the pair, else the entry-generic
    /// header, and `read_header` reads either back to the pair.
    #[test]
    fn header_of_reads_back() {
        for entry in 0..shapes::ENTRIES.len() as u16 {
            for mask in [0, 1, 2, 3, 0x7ff] {
                let header = header_of(entry, mask);
                assert_eq!(
                    header,
                    shape_id(entry, mask).unwrap_or_else(|| generic_header(entry, mask))
                );
                assert_eq!(read_header(header), Some(Header::Typed { entry, mask }));
            }
        }
    }

    /// The generated name lookups answer what a scan of the tables answers, for every name,
    /// key and word, and miss for one the tables lack.
    #[test]
    fn generated_lookups_are_the_tables_answers() {
        for (id, entry) in shapes::ENTRIES.iter().enumerate() {
            let id = id as u16;
            assert_eq!(shapes::entry_named(entry.name.as_bytes()), Some(id));
            assert_eq!(entry_id(entry.name), id);
            for (i, field) in entry.fields.iter().enumerate() {
                let first = entry.fields.iter().position(|f| f.key == field.key);
                assert_eq!(first, Some(i), "{}: key {:?} twice", entry.name, field.key);
                assert_eq!(shapes::field_named(id, field.key.as_bytes()), Some(i as u8));
                assert_eq!(field_bit(id, field.key), field.bit);
                assert_eq!(field_aux(id, field.key), field.aux);
            }
            assert_eq!(shapes::field_named(id, b"no such key"), None);
        }
        assert_eq!(shapes::entry_named(b"no such entry"), None);
        assert_eq!(
            shapes::field_named(shapes::ENTRIES.len() as u16, b"type"),
            None
        );
        for (vocab, words) in shapes::KEYWORDS.iter().enumerate() {
            let vocab = vocab as u16;
            for (i, word) in words.iter().enumerate() {
                assert_eq!(
                    shapes::keyword_named(vocab, word.as_bytes()),
                    Some(i as u32)
                );
                assert_eq!(keyword_id(vocab, word), i as u32);
            }
            assert_eq!(shapes::keyword_named(vocab, b"no such word"), None);
        }
        assert_eq!(
            shapes::keyword_named(shapes::KEYWORDS.len() as u16, b"var"),
            None
        );
    }
}
