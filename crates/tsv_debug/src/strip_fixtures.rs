/// A discovered strip fixture.
#[derive(Debug, Clone)]
pub struct StripFixture {
    /// Cwd-relative path to the fixture directory.
    pub path: PathBuf,
    /// Path relative to the strip fixture root (e.g. `hazards/statement_after_js`).
    pub relative_path: String,
    /// The input file's name (one of [`INPUTS`]).
    pub input_file: &'static str,
    /// The expected output's name, paired with the input's.
    pub expected_file: &'static str,
}

impl StripFixture {
    /// Whether this fixture matches any of the given case-insensitive substring filters
    /// (empty filters match everything).
    pub fn matches_filters(&self, filters: &[String]) -> bool {
        crate::fixtures::path_matches_filters(&self.relative_path, filters)
    }
}

/// Walk the strip fixture tree, enforcing the fixture-or-container rule: a directory holds
/// one input file (a fixture) or subdirectories (a container), never both and never
/// neither. Sorted by relative path.
///
/// # Errors
///
/// A directory breaking the rule, or one that cannot be read.
pub fn walk_strip_fixtures(root: &Path) -> Result<Vec<StripFixture>, String> {
    let mut fixtures = Vec::new();
    walk_recursive(root, "", &mut fixtures)?;
    fixtures.sort_by(|a, b| a.relative_path.cmp(&b.relative_path));
    Ok(fixtures)
}

fn walk_recursive(
    current: &Path,
    relative: &str,
    fixtures: &mut Vec<StripFixture>,
) -> Result<(), String> {
    let inputs: Vec<&(&str, &str)> = INPUTS
        .iter()
        .filter(|(input, _)| current.join(input).is_file())
        .collect();
    let mut subdirs: Vec<PathBuf> = fs::read_dir(current)
        .map_err(|e| format!("Failed to read directory {current:?}: {e}"))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    subdirs.sort();

    match inputs.as_slice() {
        [] => {}
        [(input_file, expected_file)] => {
            if !subdirs.is_empty() {
                return Err(format!(
                    "Directory {current:?} has both {input_file} and subdirectories — every \
                     directory must be a fixture or a container, not both"
                ));
            }
            fixtures.push(StripFixture {
                path: current.to_path_buf(),
                relative_path: relative.to_string(),
                input_file,
                expected_file,
            });
            return Ok(());
        }
        _ => {
            return Err(format!(
                "Directory {current:?} has more than one input file"
            ));
        }
    }
    if subdirs.is_empty() && !relative.is_empty() {
        return Err(format!(
            "Directory {current:?} has neither an input file nor subdirectories (orphan)"
        ));
    }
    for subdir in subdirs {
        let name = subdir
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or_else(|| format!("Invalid directory name: {subdir:?}"))?;
        let child_relative = if relative.is_empty() {
            name.to_string()
        } else {
            format!("{relative}/{name}")
        };
        walk_recursive(&subdir, &child_relative, fixtures)?;
    }
    Ok(())
}

/// What a finding is about. The variant order is the snapshot's line order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum StripCheck {
    /// The fixture itself is broken: a file missing, unreadable or malformed, or its
    /// expected output breaks the contract or does not parse under `tsv_ts::parse` (a
    /// TypeScript parse). Never pinned.
    Fixture,
    /// `strip` panicked. Never pinned.
    Panic,
    /// tsv's parser rejects the input.
    Parse,
    /// The output differs from the expected one (or the strip refused where the fixture
    /// expects output).
    Output,
    /// No refusal where the fixture expects one, or the wrong kind or span.
    Refusal,
    /// The output breaks position identity: a different UTF-16 length, or a kept offset
    /// holding something other than the input's character or a blank.
    Positions,
    /// The output moved, dropped, or invented a line terminator.
    Terminators,
    /// Stripping the output again changes it, or copies it.
    Idempotence,
    /// A type-free input came back copied rather than borrowed.
    Borrowed,
}

impl StripCheck {
    const ALL: [Self; 9] = [
        Self::Fixture,
        Self::Panic,
        Self::Parse,
        Self::Output,
        Self::Refusal,
        Self::Positions,
        Self::Terminators,
        Self::Idempotence,
        Self::Borrowed,
    ];

    /// The snapshot spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Fixture => "FIXTURE",
            Self::Panic => "PANIC",
            Self::Parse => "PARSE",
            Self::Output => "OUTPUT",
            Self::Refusal => "REFUSAL",
            Self::Positions => "POSITIONS",
            Self::Terminators => "TERMINATORS",
            Self::Idempotence => "IDEMPOTENCE",
            Self::Borrowed => "BORROWED",
        }
    }

    /// Whether a failure of this check may be pinned: tsv parity may, a broken fixture or a
    /// panic may not.
    pub fn is_pinnable(self) -> bool {
        !matches!(self, Self::Fixture | Self::Panic)
    }
}

/// One snapshot line: a check failing on a fixture.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct StripKey {
    /// What failed.
    pub check: StripCheck,
    /// The fixture's path relative to the tree root.
    pub fixture: String,
}

impl std::fmt::Display for StripKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{} {}", self.check.as_str(), self.fixture)
    }
}

impl SnapshotKey for StripKey {
    fn to_line(&self) -> String {
        format!("{}\t{}", self.check.as_str(), self.fixture)
    }

    fn from_line(line: &str) -> Option<Self> {
        let (check, fixture) = line.split_once('\t')?;
        let check = StripCheck::ALL.into_iter().find(|c| c.as_str() == check)?;
        Some(Self {
            check,
            fixture: fixture.to_string(),
        })
    }

    fn is_pinnable(&self) -> bool {
        self.check.is_pinnable()
    }
}

/// A failing check on one fixture, with what was found.
#[derive(Debug, Clone)]
pub struct Finding {
    /// The check and the fixture.
    pub key: StripKey,
    /// What was found, for the report.
    pub detail: String,
}

/// A refusal fixture's claim: the kind (`UnsupportedKind`'s variant name) and the span's
/// two ends as `(line, column)`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RefusalClaim {
    /// `tsv_ts::UnsupportedKind`'s variant name.
    pub kind: String,
    /// The span's start, `(1-based line, 0-based UTF-16 column)`.
    pub start: (u32, u32),
    /// The span's end, likewise.
    pub end: (u32, u32),
}

impl RefusalClaim {
    /// Parse `refusal.txt`'s one line.
    pub fn parse(content: &str) -> Option<Self> {
        let line = content.strip_suffix('\n').unwrap_or(content);
        let mut cols = line.split('\t');
        let kind = cols.next()?.to_string();
        let start = parse_point(cols.next()?)?;
        let end = parse_point(cols.next()?)?;
        if cols.next().is_some() || kind.is_empty() || line.contains('\n') {
            return None;
        }
        Some(Self { kind, start, end })
    }
}

fn parse_point(text: &str) -> Option<(u32, u32)> {
    let (line, column) = text.split_once(':')?;
    Some((line.parse().ok()?, column.parse().ok()?))
}

/// The `(line, column)` of byte offset `position` in `source`, in tsv's TypeScript
/// coordinates.
fn point_of(source: &str, position: u32) -> (u32, u32) {
    let point = tsv_ts::WIRE_COORDINATES.point(source, position as usize);
    (point.line, point.column)
}

/// A refusal of `source` as `refusal.txt` spells it — `Kind<TAB>line:column<TAB>line:column`
/// and a newline — the record the oracle side derives from ts-blank-space too.
pub fn refusal_line(source: &str, kind: tsv_ts::UnsupportedKind, span: tsv_lang::Span) -> String {
    let (start, end) = (point_of(source, span.start), point_of(source, span.end));
    format!("{kind:?}\t{}:{}\t{}:{}\n", start.0, start.1, end.0, end.1)
}

const fn is_terminator(unit: u16) -> bool {
    matches!(unit, 0x0A | 0x0D | 0x2028 | 0x2029)
}

/// What `output` breaks of the strip's contract against `input` (module docs): one finding
/// per broken check ([`StripCheck::Positions`] / [`StripCheck::Terminators`]), naming the
/// first offending input position.
pub fn contract_violations(input: &str, output: &str) -> Vec<(StripCheck, String)> {
    let a: Vec<u16> = input.encode_utf16().collect();
    let b: Vec<u16> = output.encode_utf16().collect();
    if a.len() != b.len() {
        return vec![(
            StripCheck::Positions,
            format!("UTF-16 length {} became {}", a.len(), b.len()),
        )];
    }
    let mut positions: Option<String> = None;
    let mut terminators: Option<String> = None;
    let (mut line, mut column) = (1u32, 0u32);
    for (i, (&ours, &theirs)) in a.iter().zip(&b).enumerate() {
        if ours != theirs {
            let at = format!("{line}:{column} (UTF-16 offset {i})");
            if is_terminator(ours) || is_terminator(theirs) {
                terminators
                    .get_or_insert_with(|| format!("U+{ours:04X} became U+{theirs:04X} at {at}"));
            } else if !matches!(theirs, 0x20 | 0x3B | 0x28 | 0x29) {
                positions.get_or_insert_with(|| {
                    format!(
                        "U+{ours:04X} became U+{theirs:04X} at {at} — neither kept nor a blank \
                         or a `;` / `(` / `)`"
                    )
                });
            }
        }
        // ECMAScript lines: CRLF is one terminator, so its CR ends no line
        let breaks =
            matches!(ours, 0x0A | 0x2028 | 0x2029) || (ours == 0x0D && a.get(i + 1) != Some(&0x0A));
        if breaks {
            line += 1;
            column = 0;
        } else {
            column += 1;
        }
    }
    let mut found = Vec::new();
    if let Some(detail) = positions {
        found.push((StripCheck::Positions, detail));
    }
    if let Some(detail) = terminators {
        found.push((StripCheck::Terminators, detail));
    }
    found
}

/// The fixture's claim, read from disk.
enum Claim {
    Expected(String),
    Refusal(RefusalClaim),
}

/// Run every check on one fixture.
pub fn check_fixture(fixture: &StripFixture) -> Vec<Finding> {
    let mut findings = Vec::new();
    let mut push = |check: StripCheck, detail: String| {
        findings.push(Finding {
            key: StripKey {
                check,
                fixture: fixture.relative_path.clone(),
            },
            detail,
        });
    };

    let Some((input, claim)) = read_fixture(fixture, &mut push) else {
        return findings;
    };

    // fixture integrity: the expected output keeps the contract and parses (a TypeScript
    // parse; JS validity is the oracle script's oxc check)
    if let Claim::Expected(expected) = &claim {
        for (_, detail) in contract_violations(&input, expected) {
            push(
                StripCheck::Fixture,
                format!("{} breaks the contract: {detail}", fixture.expected_file),
            );
        }
        let arena = bumpalo::Bump::new();
        if let Err(e) = tsv_ts::parse(expected, &arena) {
            push(
                StripCheck::Fixture,
                format!(
                    "{} does not parse (tsv_ts::parse): {e}",
                    fixture.expected_file
                ),
            );
        }
    }

    let arena = bumpalo::Bump::new();
    let Ok(result) = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        tsv_ts::strip(&input, &arena)
    })) else {
        push(StripCheck::Panic, "strip panicked".to_string());
        return findings;
    };

    match (&claim, result) {
        (_, Err(tsv_ts::StripError::Parse(e))) => {
            push(
                StripCheck::Parse,
                format!("tsv's parser rejects the input: {e}"),
            );
        }
        (Claim::Expected(_), Err(tsv_ts::StripError::Unsupported { kind, span })) => push(
            StripCheck::Output,
            format!(
                "refused {kind:?} at {:?}–{:?} where the fixture expects output",
                point_of(&input, span.start),
                point_of(&input, span.end)
            ),
        ),
        (Claim::Expected(expected), Ok(stripped)) => {
            let code = stripped.code.as_ref();
            if code != expected {
                push(StripCheck::Output, first_difference(expected, code));
            }
            for (check, detail) in contract_violations(&input, code) {
                push(check, detail);
            }
            if *expected == input && matches!(stripped.code, Cow::Owned(_)) {
                push(
                    StripCheck::Borrowed,
                    "nothing is type-only, yet the output is a copy".to_string(),
                );
            }
            match idempotence_failure(&input, code) {
                Some(failure) if failure.is_panic() => {
                    push(StripCheck::Panic, failure.to_string());
                }
                Some(failure) => push(StripCheck::Idempotence, failure.to_string()),
                None => {}
            }
        }
        (Claim::Refusal(claimed), Ok(_)) => push(
            StripCheck::Refusal,
            format!(
                "stripped where the fixture expects a refusal ({} {:?}–{:?})",
                claimed.kind, claimed.start, claimed.end
            ),
        ),
        (Claim::Refusal(claimed), Err(tsv_ts::StripError::Unsupported { kind, span })) => {
            let got = RefusalClaim {
                kind: format!("{kind:?}"),
                start: point_of(&input, span.start),
                end: point_of(&input, span.end),
            };
            if got != *claimed {
                push(
                    StripCheck::Refusal,
                    format!(
                        "refused {} {:?}–{:?}; the fixture expects {} {:?}–{:?}",
                        got.kind, got.start, got.end, claimed.kind, claimed.start, claimed.end
                    ),
                );
            }
        }
    }
    findings
}

/// Read the input and the claim, pushing a [`StripCheck::Fixture`] finding for anything
/// malformed (and `None` when the fixture cannot be graded at all).
fn read_fixture(
    fixture: &StripFixture,
    push: &mut impl FnMut(StripCheck, String),
) -> Option<(String, Claim)> {
    if let Ok(entries) = fs::read_dir(&fixture.path) {
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            let allowed = name == fixture.input_file
                || name == fixture.expected_file
                || name == REFUSAL_FILE
                || name == DIVERGENCES_FILE
                || name == README_FILE;
            if !allowed || entry.path().is_dir() {
                push(StripCheck::Fixture, format!("unexpected entry {name}"));
            }
        }
    }
    if !fixture.path.join(README_FILE).is_file() {
        push(StripCheck::Fixture, format!("missing {README_FILE}"));
    }
    let divergences_path = fixture.path.join(DIVERGENCES_FILE);
    if divergences_path.is_file() {
        let content = fs::read_to_string(&divergences_path).unwrap_or_default();
        if let Some(detail) = divergences_failure(&content) {
            push(StripCheck::Fixture, format!("{DIVERGENCES_FILE}: {detail}"));
        }
    }
    let input = match fs::read_to_string(fixture.path.join(fixture.input_file)) {
        Ok(input) => input,
        Err(e) => {
            push(
                StripCheck::Fixture,
                format!("cannot read {}: {e}", fixture.input_file),
            );
            return None;
        }
    };
    let expected_path = fixture.path.join(fixture.expected_file);
    let refusal_path = fixture.path.join(REFUSAL_FILE);
    let claim = match (expected_path.is_file(), refusal_path.is_file()) {
        (true, false) => match fs::read_to_string(&expected_path) {
            Ok(expected) => Claim::Expected(expected),
            Err(e) => {
                push(
                    StripCheck::Fixture,
                    format!("cannot read {}: {e}", fixture.expected_file),
                );
                return None;
            }
        },
        (false, true) => {
            let content = fs::read_to_string(&refusal_path).unwrap_or_default();
            let Some(claim) = RefusalClaim::parse(&content) else {
                push(
                    StripCheck::Fixture,
                    format!("malformed {REFUSAL_FILE} — expected `Kind<TAB>line:col<TAB>line:col`"),
                );
                return None;
            };
            Claim::Refusal(claim)
        }
        (both, _) => {
            push(
                StripCheck::Fixture,
                format!(
                    "{} — exactly one of {} and {REFUSAL_FILE}; regenerate with \
                     `deno task strip:fixtures:update`",
                    if both {
                        "both claims present"
                    } else {
                        "no claim"
                    },
                    fixture.expected_file
                ),
            );
            return None;
        }
    };
    Some((input, claim))
}

/// What is wrong with a `divergences.txt`, if anything: a line outside
/// [`DIVERGENCE_LINES`], an oracle named twice (plain and overridden included), or no line.
fn divergences_failure(content: &str) -> Option<String> {
    let mut seen = BTreeSet::new();
    for line in content.lines().map(str::trim).filter(|l| !l.is_empty()) {
        if !DIVERGENCE_LINES.contains(&line) {
            return Some(format!(
                "unknown line `{line}` — expected one of {}",
                DIVERGENCE_LINES.join(", ")
            ));
        }
        let oracle = line.strip_prefix("override ").unwrap_or(line);
        if !seen.insert(oracle) {
            return Some(format!("{oracle} is named twice"));
        }
    }
    seen.is_empty().then(|| "empty".to_string())
}

/// Why stripping a strip's output again is not the identity on a borrowed source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IdempotenceFailure {
    /// The second strip panicked: [`caught_panic_report`]'s text, with the location under
    /// a capturing panic hook.
    Panicked(String),
    /// The second strip failed (a parse error or a refusal).
    Fails(String),
    /// The second strip copied the output unchanged (type syntax survived?).
    Copies,
    /// The second strip changed the output, outside what [`only_reread_type_arguments`]
    /// excuses; the first difference.
    Changes(String),
}

impl IdempotenceFailure {
    /// Whether the second strip panicked — a panic finding, not a contract one.
    pub const fn is_panic(&self) -> bool {
        matches!(self, Self::Panicked(_))
    }
}

impl std::fmt::Display for IdempotenceFailure {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Panicked(report) => write!(f, "stripping the output panicked: {report}"),
            Self::Fails(error) => write!(f, "stripping the output fails: {error}"),
            Self::Copies => f.write_str("stripping the output copies it (type syntax survived?)"),
            Self::Changes(difference) => write!(f, "stripping the output changes it: {difference}"),
        }
    }
}

/// Why stripping `code` — the strip of `input` — again is not the identity on a borrowed
/// source, if it is not.
///
/// One re-strip difference is excused: the JS/TS ambiguity of `<`. The output is JS, yet
/// the second strip reads it as TypeScript, where a comparison pair may read as a
/// type-argument list — `f(a < b, c as any > (d))` strips to `f(a < b, c        > (d))`,
/// both comparisons as tsv read the input, and re-read as TypeScript that is the generic
/// call `a<b, c>(d)`, whose list the second strip blanks. The first output is the right one
/// (ts-blank-space's and Node's bytes), so a re-strip whose every change is the blanking of
/// such a list is not a failure ([`only_reread_type_arguments`]); any other change is.
pub fn idempotence_failure(input: &str, code: &str) -> Option<IdempotenceFailure> {
    let arena = bumpalo::Bump::new();
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| tsv_ts::strip(code, &arena))) {
        Err(payload) => Some(IdempotenceFailure::Panicked(caught_panic_report(
            payload.as_ref(),
        ))),
        Ok(Err(e)) => Some(IdempotenceFailure::Fails(e.to_string())),
        Ok(Ok(again)) => match again.code {
            Cow::Borrowed(_) => None,
            Cow::Owned(again) if again == code => Some(IdempotenceFailure::Copies),
            Cow::Owned(again) if only_reread_type_arguments(input, code, &again) => None,
            Cow::Owned(again) => Some(IdempotenceFailure::Changes(first_difference(code, &again))),
        },
    }
}

/// Whether `again` — the strip of `code`, itself the strip of `input` — differs from
/// `code` only by blanking type-argument lists that `code` holds and `input` did not: each
/// changed UTF-16 unit is a space, and lies inside the `typeArguments` of a call, a `new`,
/// a tagged template or an instantiation expression in `code`'s parse whose span is no
/// such list in `input`'s parse. The strip keeps UTF-16 offsets, so the two parses' spans
/// share coordinates.
///
/// A list `input` already held is never excused: a first strip that left it in place
/// missed it. Nor is any other change — a leftover annotation, a modifier, a `;` / `(` /
/// `)` substitution — or a change in length.
fn only_reread_type_arguments(input: &str, code: &str, again: &str) -> bool {
    let code_units: Vec<u16> = code.encode_utf16().collect();
    let again_units: Vec<u16> = again.encode_utf16().collect();
    if code_units.len() != again_units.len() {
        return false;
    }
    let held = type_argument_lists(input);
    let reread: Vec<(usize, usize)> = type_argument_lists(code)
        .into_iter()
        .filter(|list| !held.contains(list))
        .collect();
    code_units
        .iter()
        .zip(&again_units)
        .enumerate()
        .filter(|(_, (ours, theirs))| ours != theirs)
        .all(|(i, (_, &theirs))| {
            theirs == u16::from(b' ') && reread.iter().any(|&(start, end)| start <= i && i < end)
        })
}

/// The UTF-16 spans of every expression-level type-argument list in `source`'s parse — the
/// `typeArguments` of a `CallExpression`, `NewExpression`, `TaggedTemplateExpression` or
/// `TSInstantiationExpression` on the wire, which carries UTF-16 offsets. Read as the strip
/// reads it (the unset-goal fallback); empty when `source` does not parse.
fn type_argument_lists(source: &str) -> BTreeSet<(usize, usize)> {
    let mut lists = BTreeSet::new();
    let Some(wire) = tsv_parse_to_value(source, ParserType::TypeScript) else {
        return lists;
    };
    let span = |node: &serde_json::Value| {
        let start = usize::try_from(node.get("start")?.as_u64()?).ok()?;
        let end = usize::try_from(node.get("end")?.as_u64()?).ok()?;
        Some((start, end))
    };
    let mut stack = vec![&wire];
    while let Some(value) = stack.pop() {
        match value {
            serde_json::Value::Object(node) => {
                let instantiates = matches!(
                    node.get("type").and_then(serde_json::Value::as_str),
                    Some(
                        "CallExpression"
                            | "NewExpression"
                            | "TaggedTemplateExpression"
                            | "TSInstantiationExpression"
                    )
                );
                if instantiates && let Some(list) = node.get("typeArguments").and_then(span) {
                    lists.insert(list);
                }
                stack.extend(node.values());
            }
            serde_json::Value::Array(items) => stack.extend(items),
            _ => {}
        }
    }
    lists
}

/// The first line where `actual` departs from `expected`, both escaped.
fn first_difference(expected: &str, actual: &str) -> String {
    let mut expected_lines = expected.split_inclusive('\n');
    let mut actual_lines = actual.split_inclusive('\n');
    let mut line = 1;
    loop {
        match (expected_lines.next(), actual_lines.next()) {
            (Some(a), Some(b)) if a == b => line += 1,
            (None, None) => return "outputs differ".to_string(),
            (a, b) => {
                return format!(
                    "first difference on line {line}: expected {:?}, got {:?}",
                    a.unwrap_or(""),
                    b.unwrap_or("")
                );
            }
        }
    }
}

/// The strip ratchet's verdict over a run.
#[derive(Debug)]
pub struct GateReport {
    /// Fixtures checked.
    pub fixtures: usize,
    /// Every failing check, in fixture order.
    pub findings: Vec<Finding>,
    /// Pinnable failures not in the snapshot.
    pub new: Vec<StripKey>,
    /// Snapshot lines (within the run's scope) that no longer fail.
    pub stale: Vec<StripKey>,
    /// Failures that may never be pinned.
    pub unpinnable: Vec<StripKey>,
    /// Snapshot lines within the run's scope.
    pub known: usize,
    /// The pinnable failures found — what `--update` writes.
    pub pinnable: BTreeSet<StripKey>,
}

impl GateReport {
    /// Whether the ratchet holds: nothing new, nothing stale, nothing unpinnable.
    pub fn holds(&self) -> bool {
        self.new.is_empty() && self.stale.is_empty() && self.unpinnable.is_empty()
    }
}

fn ratchet() -> Ratchet {
    Ratchet::colocated(KNOWN_FILE, SNAPSHOT_HEADER, REPIN_HINT)
}

/// Check every fixture under [`STRIP_FIXTURES_DIR`] matching `filters` and grade the
/// failures against the snapshot. A filtered run grades against the snapshot's lines for
/// the fixtures it reached.
///
/// # Errors
///
/// The tree breaks the hierarchy rule, matches no fixture, or the snapshot is unreadable.
pub fn run_gate(filters: &[String]) -> Result<GateReport, String> {
    let fixtures: Vec<StripFixture> = walk_strip_fixtures(Path::new(STRIP_FIXTURES_DIR))?
        .into_iter()
        .filter(|f| f.matches_filters(filters))
        .collect();
    if fixtures.is_empty() {
        return Err(format!(
            "no strip fixtures matched under {STRIP_FIXTURES_DIR}"
        ));
    }
    let findings: Vec<Finding> = fixtures.iter().flat_map(check_fixture).collect();
    let in_scope: BTreeSet<&str> = fixtures.iter().map(|f| f.relative_path.as_str()).collect();
    let known: BTreeSet<StripKey> = ratchet()
        .parse_known::<StripKey>()
        .map_err(|_| "cannot read the strip ratchet snapshot".to_string())?
        .into_iter()
        .filter(|k| in_scope.contains(k.fixture.as_str()))
        .collect();
    let pinnable: BTreeSet<StripKey> = findings
        .iter()
        .map(|f| f.key.clone())
        .filter(|k| k.check.is_pinnable())
        .collect();
    let unpinnable: Vec<StripKey> = findings
        .iter()
        .map(|f| f.key.clone())
        .filter(|k| !k.check.is_pinnable())
        .collect();
    Ok(GateReport {
        fixtures: fixtures.len(),
        new: pinnable.difference(&known).cloned().collect(),
        stale: known.difference(&pinnable).cloned().collect(),
        known: known.len(),
        unpinnable,
        findings,
        pinnable,
    })
}

/// Write `found` as the snapshot. The caller refuses a filtered run, whose failures are a
/// subset of what the snapshot means.
///
/// # Errors
///
/// The snapshot cannot be written.
pub fn write_known(found: &BTreeSet<StripKey>) -> Result<(), String> {
    ratchet()
        .write(found)
        .map_err(|_| "cannot write the strip ratchet snapshot".to_string())
}

/// The snapshot's path, for reporting.
pub fn known_path() -> PathBuf {
    ratchet().path().to_path_buf()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn contract_accepts_blanks_and_substitutions() {
        assert!(contract_violations("let a: T = b\n(c)", "let a    = b\n(c)").is_empty());
        assert!(contract_violations("a as T\n(c)", "a;    \n(c)").is_empty());
        assert!(contract_violations("let a: 'é' = 1", "let a      = 1").is_empty());
        assert!(contract_violations("x\r\ny\u{2028}", "x\r\ny\u{2028}").is_empty());
    }

    #[test]
    fn contract_rejects_moved_terminators_and_foreign_characters() {
        let terminator = contract_violations("a:\u{2028}T", "a  T");
        assert_eq!(terminator.len(), 1);
        assert_eq!(terminator[0].0, StripCheck::Terminators);
        let foreign = contract_violations("a: T", "a: X");
        assert_eq!(foreign[0].0, StripCheck::Positions);
        let length = contract_violations("a: T", "a");
        assert_eq!(length[0].0, StripCheck::Positions);
    }

    #[test]
    fn contract_reports_ecmascript_lines() {
        // CRLF is one terminator; a lone CR and U+2028 each end a line
        let found = contract_violations("a\r\nb\rc\u{2028}d: T", "a\r\nb\rc\u{2028}dX  ");
        assert_eq!(found.len(), 1);
        assert!(found[0].1.contains("at 4:1 "), "{}", found[0].1);
    }

    /// The JS/TS ambiguity: the output's comparison pair re-reads as TypeScript's generic
    /// call `a<b, c>(d)`, whose list the second strip blanks. Excused — the first output is
    /// the right one.
    #[test]
    fn a_reread_type_argument_list_is_not_an_idempotence_failure() {
        let input = "f(a < b, c as any > (d));\n";
        let code = "f(a < b, c        > (d));\n";
        let arena = bumpalo::Bump::new();
        let again = tsv_ts::strip(code, &arena).expect("the output strips");
        assert_eq!(
            again.code, "f(a                 (d));\n",
            "the re-read the excuse is for"
        );
        assert!(only_reread_type_arguments(input, code, &again.code));
        assert_eq!(idempotence_failure(input, code), None);
    }

    /// Every other re-strip change still fails: a first strip that left an annotation in
    /// place (here beside an excused list, which excuses nothing else), and one that left a
    /// type-argument list the input already held.
    #[test]
    fn a_restrip_change_outside_a_reread_list_still_fails() {
        let input = "let y: T = f(a < b, c as any > (d));\n";
        let leftover_annotation = "let y: T = f(a < b, c        > (d));\n";
        assert!(matches!(
            idempotence_failure(input, leftover_annotation),
            Some(IdempotenceFailure::Changes(_))
        ));
        let input = "f<T>(x);\n";
        assert!(matches!(
            idempotence_failure(input, input),
            Some(IdempotenceFailure::Changes(_))
        ));
    }

    /// Inside a re-read list only a blank is excused, and the length must hold.
    #[test]
    fn a_reread_list_excuses_blanks_alone() {
        let input = "f(a < b, c as any > (d));\n";
        let code = "f(a < b, c        > (d));\n";
        assert!(only_reread_type_arguments(
            input,
            code,
            "f(a                 (d));\n"
        ));
        assert!(!only_reread_type_arguments(
            input,
            code,
            "f(a   ;             (d));\n"
        ));
        assert!(!only_reread_type_arguments(input, code, "f(a (d));\n"));
    }

    /// The excuse ends at the list's `>`: the unit right after it is not excused, nor is a
    /// shorter re-strip whose every surviving unit would pass.
    #[test]
    fn a_reread_list_excuses_nothing_past_its_end_or_a_length_change() {
        let input = "f(a < b, c as any >(d));\n";
        let code = "f(a < b, c        >(d));\n";
        assert!(only_reread_type_arguments(
            input,
            code,
            "f(a                (d));\n"
        ));
        assert!(!only_reread_type_arguments(
            input,
            code,
            "f(a                 d));\n"
        ));
        assert!(!only_reread_type_arguments(
            input,
            code,
            "f(a                "
        ));
    }

    #[test]
    fn refusal_claim_round_trips() {
        let claim = RefusalClaim::parse("Enum\t1:0\t3:1\n").expect("claim parses");
        assert_eq!(claim.kind, "Enum");
        assert_eq!((claim.start, claim.end), ((1, 0), (3, 1)));
        assert!(RefusalClaim::parse("Enum\t1:0\n").is_none());
        assert!(RefusalClaim::parse("Enum\t1:0\t3:1\textra\n").is_none());
    }

    #[test]
    fn divergences_lines() {
        assert_eq!(divergences_failure("node\n"), None);
        assert_eq!(divergences_failure("override ts-blank-space\nnode\n"), None);
        assert!(divergences_failure("").is_some());
        assert!(divergences_failure("override node\n").is_some());
        assert!(divergences_failure("ts-blank-space\noverride ts-blank-space\n").is_some());
        assert!(divergences_failure("prettier\n").is_some());
    }

    #[test]
    fn snapshot_key_round_trips() {
        let key = StripKey {
            check: StripCheck::Output,
            fixture: "erase/interface".to_string(),
        };
        assert_eq!(StripKey::from_line(&key.to_line()), Some(key));
        assert_eq!(StripKey::from_line("NOPE\tx"), None);
        assert!(!StripCheck::Fixture.is_pinnable());
        assert!(!StripCheck::Panic.is_pinnable());
    }
}
