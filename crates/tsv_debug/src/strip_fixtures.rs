//! Strip-fixture discovery, file conventions, and the checks `tsv_ts::strip` is graded by.
//!
//! The source type strip's fixtures live in their own tree — `tests/fixtures_strip/` — since
//! their claim is not the parse/format one `tests/fixtures/` makes. Each fixture directory
//! holds:
//!
//! - one input: `input.ts`, `input.mts`, or `input.svelte.ts`;
//! - its claim, exactly one of
//!   - `expected.js` / `expected.mjs` / `expected.svelte.js` — the stripped JS, or
//!   - `refusal.txt` — `UnsupportedKind<TAB>line:column<TAB>line:column`: the refused kind
//!     and its span's two ends (1-based line, 0-based UTF-16 column, ECMAScript line
//!     terminators — `tsv_ts::WIRE_COORDINATES`);
//! - optionally `divergences.txt` — the oracles the claim departs from, one per line
//!   ([`DIVERGENCE_LINES`]);
//! - `README.md` — what the fixture pins, and why for each divergence.
//!
//! Both claim files are oracle-generated (ts-blank-space, cross-checked against Node's
//! `module.stripTypeScriptTypes`) by `deno task strip:fixtures:update`, except under an
//! `override ts-blank-space` line, where ts-blank-space is wrong and the committed claim is
//! hand-reviewed; `deno task strip:fixtures:oracle` re-checks both kinds. This module grades
//! tsv against the committed files, needing neither oracle, and holds a reviewed claim to
//! the same checks as a generated one.
//!
//! Two classes of check, kept apart by [`StripCheck::is_pinnable`]:
//!
//! - **Fixture integrity** (unpinnable, always failing): the files are well-formed, and the
//!   expected output itself keeps the contract below and parses under `tsv_ts::parse` at
//!   module goal. These hold whatever tsv's strip does. That parse is a TypeScript one, so it
//!   cannot prove the output is JS; the JS-validity guard is the oracle script's
//!   oxc-parser parse in JS mode.
//! - **tsv parity** (pinnable): `tsv_ts::strip` produces the claim, keeps the contract, and
//!   is idempotent. A known failure is pinned in the ratchet snapshot
//!   `src/cli/commands/strip_fixtures_known.txt` (the `audit::ratchet` convention): a new
//!   failure fails the gate, and so does a pinned one that stopped failing.
//!
//! **The contract** ([`contract_violations`]): the output has the input's UTF-16 length;
//! every line terminator (LF, CR, U+2028, U+2029) sits at the same UTF-16 offset in both;
//! and every other offset holds the input's character or a blank — a space, or one of the
//! `;` / `(` / `)` hazard substitutions. Every character the strip keeps therefore keeps its
//! line and UTF-16 column, which is the invariant V8's stack traces need.
//!
//! The contract's known limit: a blank is allowed at any offset, not only inside a type-only
//! range or at a hazard site, so deleted JS or a misplaced `;` passes it and is
//! caught only by the comparison with the expected output.

